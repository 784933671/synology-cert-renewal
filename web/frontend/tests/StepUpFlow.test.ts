import { afterEach, describe, expect, it, vi } from 'vitest'
import { defineComponent, h } from 'vue'
import { flushPromises, mount, type VueWrapper } from '@vue/test-utils'
import { useStepUp } from '../src/composables/useStepUp'
import { api, setCsrf } from '../src/lib/api'
let wrapper: VueWrapper | undefined, flow: ReturnType<typeof useStepUp>
const meta = { challenge_id: 'challenge-a', email_masked: 'a***@example.com', expires_in: 300, resend_after: 60, operation: 'actions.renew' }
const reply = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status })
const required = () => reply({ error: { code: 'stepup_required', message: '需要验证' } }, 428)
function start() { wrapper = mount(defineComponent({ setup() { flow = useStepUp(); return () => h('div') } })) }
async function begin(fetcher: ReturnType<typeof vi.fn>, controller?: AbortController) {
  vi.stubGlobal('fetch', fetcher)
  start()
  const pending = api('/api/actions/renew', { method: 'POST', body: { confirmed: true }, signal: controller?.signal })
  const result = pending.then(value => ({ value }), error => ({ error }))
  await flushPromises()
  return { result }
}
afterEach(() => { wrapper?.unmount(); setCsrf(''); vi.unstubAllGlobals(); vi.useRealTimers() })
describe('二次验证交互生命周期', () => {
  it('用户主动发送、校验通过后才执行，避免双击重复操作', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(required()).mockResolvedValueOnce(reply(meta)).mockResolvedValueOnce(reply({ token: 'grant', expires_in: 120 })).mockResolvedValueOnce(reply({ ok: true }))
    const { result } = await begin(fetcher)
    expect(flow.open.value).toBe(true)
    expect(fetcher).toHaveBeenCalledOnce()
    await flow.send()
    expect(flow.challenge.value?.email_masked).toBe(meta.email_masked)
    await Promise.all([flow.verify('123456'), flow.verify('123456')])
    expect(await result).toEqual({ value: { ok: true } })
    expect(fetcher.mock.calls.map(([path]) => path)).toEqual(['/api/actions/renew', '/api/stepup/start', '/api/stepup/verify', '/api/actions/renew'])
    expect(flow.open.value).toBe(false)
    expect(flow.challenge.value).toBeNull()
  })
  it('错误码可更正，过期后禁用验证且重发遵守冷却', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(required()).mockResolvedValueOnce(reply(meta))
      .mockResolvedValueOnce(reply({ error: { code: 'invalid_code', message: '验证码不正确' } }, 400))
      .mockResolvedValueOnce(reply({ error: { code: 'stepup_expired', message: '验证码已失效' } }, 410))
      .mockResolvedValue(reply({ ok: true }))
    const { result } = await begin(fetcher)
    await flow.send()
    await flow.send(true)
    expect(fetcher).toHaveBeenCalledTimes(2)
    await flow.verify('１２３４５６')
    expect(flow.error.value).toContain('6 位数字')
    await flow.verify('111111')
    expect(flow.error.value).toBe('验证码不正确')
    expect(flow.verifyUnknown.value).toBe(false)
    await flow.verify('222222')
    await flow.verify('333333')
    expect(fetcher).toHaveBeenCalledTimes(4)
    flow.cancel()
    expect(await result).toMatchObject({ error: { code: 'stepup_cancelled' } })
  })
  it('发送结果未知只能显式恢复同一操作，不自动重发或执行', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(required()).mockRejectedValueOnce(new Error('lost'))
      .mockResolvedValueOnce(reply(meta)).mockResolvedValue(reply({ ok: true }))
    const { result } = await begin(fetcher)
    await flow.send()
    expect(flow.recoverSend.value).toBe(true)
    expect(fetcher).toHaveBeenCalledTimes(2)
    await flow.verify('123456')
    expect(fetcher).toHaveBeenCalledTimes(2)
    await flow.send()
    expect(fetcher.mock.calls[1][1].body).toBe(fetcher.mock.calls[2][1].body)
    expect(flow.recoverSend.value).toBe(false)
    flow.cancel()
    await result
  })
  it('邮件503后显式恢复失败挑战，冷却结束可重发并完成同一操作', async () => {
    vi.useFakeTimers()
    const fetcher = vi.fn().mockResolvedValueOnce(required())
      .mockResolvedValueOnce(reply({ error: { code: 'mail_unavailable', message: '邮件服务不可用' } }, 503))
      .mockResolvedValueOnce(reply({ ...meta, expires_in: 0, resend_after: 1 }))
      .mockResolvedValueOnce(reply(meta)).mockResolvedValueOnce(reply({ token: 'grant' })).mockResolvedValueOnce(reply({ ok: true }))
    const { result } = await begin(fetcher)
    await flow.send()
    expect(flow.recoverSend.value).toBe(true)
    expect(fetcher).toHaveBeenCalledTimes(2)
    await flow.send()
    expect(flow.expiresIn.value).toBe(0)
    await flow.send(true)
    expect(fetcher).toHaveBeenCalledTimes(3)
    await vi.advanceTimersByTimeAsync(1000)
    await flow.send(true)
    expect(fetcher.mock.calls[3][0]).toBe('/api/stepup/resend')
    await flow.verify('123456')
    expect(await result).toEqual({ value: { ok: true } })
  })
  it('重发429先恢复服务器冷却，冷却后可以继续，绝不自动再发码', async () => {
    vi.useFakeTimers()
    const fetcher = vi.fn().mockResolvedValueOnce(required()).mockResolvedValueOnce(reply({ ...meta, resend_after: 0 }))
      .mockResolvedValueOnce(reply({ error: { code: 'rate_limited', message: '发送过于频繁' } }, 429))
      .mockResolvedValueOnce(reply({ ...meta, resend_after: 20 })).mockResolvedValueOnce(reply(meta)).mockResolvedValue(reply({ ok: true }))
    const { result } = await begin(fetcher)
    await flow.send()
    await flow.send(true)
    expect(flow.recoverSend.value).toBe(true)
    expect(fetcher).toHaveBeenCalledTimes(3)
    await flow.send()
    expect(flow.resendAfter.value).toBe(20)
    await flow.send(true)
    expect(fetcher).toHaveBeenCalledTimes(4)
    await vi.advanceTimersByTimeAsync(20000)
    await flow.send(true)
    expect(fetcher.mock.calls[4][0]).toBe('/api/stepup/resend')
    flow.cancel()
    await result
  })
  it.each(['验证码错误次数过多', '二次验证已过期'])('%s时可取消并重新发起，旧操作不执行', async (message) => {
    const fetcher = vi.fn().mockResolvedValueOnce(required()).mockResolvedValueOnce(reply(meta))
      .mockResolvedValueOnce(reply({ error: { code: 'stepup_expired', message } }, 410))
      .mockResolvedValueOnce(reply({ ok: true })).mockResolvedValueOnce(required()).mockResolvedValueOnce(reply({ ...meta, challenge_id: 'challenge-b' }))
      .mockResolvedValue(reply({ ok: true }))
    const { result } = await begin(fetcher)
    await flow.send()
    await flow.verify('123456')
    expect(flow.expiresIn.value).toBe(0)
    flow.cancel()
    expect(await result).toMatchObject({ error: { code: 'stepup_cancelled' } })
    const next = api('/api/actions/renew', { method: 'POST', body: { confirmed: true } }).catch(error => error)
    await flushPromises()
    expect(flow.open.value).toBe(true)
    await flow.send()
    expect(flow.challenge.value?.challenge_id).toBe('challenge-b')
    flow.cancel()
    await next
    expect(fetcher.mock.calls.filter(([path, options]) => path === '/api/actions/renew' && options.headers['X-Step-Up-Token'])).toHaveLength(0)
  })
  it('验证码验证响应丢失不取回授权、不重发业务，只允许取消重新发起', async () => {
    const fetcher = vi.fn().mockResolvedValueOnce(required()).mockResolvedValueOnce(reply(meta))
      .mockRejectedValueOnce(new Error('lost')).mockResolvedValue(reply({ ok: true }))
    const { result } = await begin(fetcher)
    await flow.send()
    await flow.verify('123456')
    expect(flow.verifyUnknown.value).toBe(true)
    expect(flow.error.value).toContain('业务操作未执行')
    await flow.verify('123456')
    await flow.send(true)
    expect(fetcher).toHaveBeenCalledTimes(3)
    flow.cancel()
    await result
    expect(fetcher.mock.calls.filter(([path]) => path === '/api/actions/renew')).toHaveLength(1)
  })
  it.each(['cancel', 'abort', 'unmount', 'session'])('%s清理后迟到授权不能执行操作', async (reason) => {
    let finish!: (value: Response) => void
    const controller = new AbortController()
    const fetcher = vi.fn().mockResolvedValueOnce(required()).mockResolvedValueOnce(reply(meta))
      .mockImplementationOnce(() => new Promise<Response>((resolve) => { finish = resolve }))
      .mockResolvedValue(reply({ ok: true }))
    const { result } = await begin(fetcher, controller)
    await flow.send()
    const verifying = flow.verify('123456')
    if (reason === 'abort') controller.abort()
    else if (reason === 'unmount') { wrapper?.unmount(); wrapper = undefined }
    else flow.cancel(reason !== 'session')
    finish(reply({ token: 'stale-grant' }))
    await verifying
    expect(await result).toHaveProperty('error')
    expect(flow.open.value).toBe(false)
    expect(fetcher.mock.calls.filter(([path]) => path === '/api/actions/renew')).toHaveLength(1)
  })
  it('并发敏感操作不覆盖当前挑战', async () => {
    const fetcher = vi.fn().mockImplementation(() => Promise.resolve(required()))
    const { result } = await begin(fetcher)
    await expect(api('/api/security', { method: 'PUT' })).rejects.toMatchObject({ code: 'stepup_busy' })
    expect(flow.operation.value).toBe('立即申请并替换证书')
    flow.cancel()
    await result
  })
})
